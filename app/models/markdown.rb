# Renders exercise bodies, which are authored as Markdown in db/exercises/.
# The choice of renderer and the reasoning behind both layers below are recorded
# in docs/decisions/0003-markdown-rendering.md.
class Markdown
  # Commonmarker already drops raw HTML, so this allowlist is the second of two
  # independent layers rather than the only one. It exists because body_md stops
  # being trusted content the moment organizations can author exercises
  # (codegym-nmf), and a guard added in advance is one that cannot be forgotten
  # under deadline.
  TAGS = %w[
    p br hr
    h1 h2 h3 h4 h5 h6
    ul ol li
    strong em del
    code pre
    blockquote
    a
    table thead tbody tr th td
  ].freeze

  # lang survives on <pre> because that is where Commonmarker records a fenced
  # block's language, and syntax highlighting later will want it. No img and no
  # class: exercises are text, and neither has a use yet.
  ATTRIBUTES = %w[href title lang].freeze

  OPTIONS = {
    # Raw HTML in the source is omitted rather than passed through.
    render: { unsafe: false },
    extension: {
      table: true,
      strikethrough: true,
      # No autogenerated heading anchors: they add an empty link and an
      # aria-label to every heading, which is noise in a page this short.
      header_ids: nil
    }
  }.freeze

  # Syntax highlighting is on by default and inlines a fixed dark theme as style
  # attributes on every token. That bloats the HTML, ignores the reader's colour
  # scheme, and would be stripped by the sanitizer anyway. Off, so a fenced block
  # is a plain <pre lang="..."><code>.
  PLUGINS = { syntax_highlighter: nil }.freeze

  def self.render(text)
    new(text).to_html
  end

  def self.sanitizer
    @sanitizer ||= Rails::HTML5::SafeListSanitizer.new
  end

  def initialize(text)
    # Commonmarker raises TypeError on anything that is not UTF-8, and that
    # includes the US-ASCII empty string nil.to_s produces. scrub drops invalid
    # byte sequences rather than letting them reach the renderer.
    @text = text.to_s.dup.force_encoding(Encoding::UTF_8).scrub
  end

  def to_html
    sanitized.html_safe
  end

  private
    def sanitized
      self.class.sanitizer.sanitize(rendered, tags: TAGS, attributes: ATTRIBUTES)
    end

    def rendered
      Commonmarker.to_html(@text, options: OPTIONS, plugins: PLUGINS)
    end
end
